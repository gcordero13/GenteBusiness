-- Narrow, bounded write path: complaints keeps its existing zero-UPDATE-policy
-- guarantee (verified by "direct update/delete against complaints is rejected
-- for everyone" in complaints.test.ts) for message/category/is_anonymous/
-- contact_id/photo_path - none of those become editable. This function is the
-- ONLY way to change a complaint after submission, and it can only ever touch
-- status/reviewer_comment.
create or replace function public.update_complaint_status(p_id uuid, p_status text, p_comment text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.can_view_complaints() then
    raise exception 'not authorized';
  end if;

  update public.complaints
  set status = p_status, reviewer_comment = p_comment
  where id = p_id;
end;
$$;

-- submit_complaint grows an optional p_photo_path parameter, which changes
-- its argument TYPE LIST (text, text, boolean) -> (text, text, boolean,
-- text). Postgres identifies a function by name + argument types, not by
-- name alone, so CREATE OR REPLACE would not replace the old 3-arg overload -
-- it would silently create a second, coexisting function and leave the old
-- one live forever. Drop the old overload first (same lesson already learned
-- in 20260814100000_ponchador_overview_tab.sql).
drop function if exists public.submit_complaint(text, text, boolean);

-- submit_complaint grows an optional p_photo_path: a storage path string
-- (never derived from or containing the uploader's identity - it's a random
-- key generated by the Server Action before calling this function), stored
-- identically whether the complaint is anonymous or named. One code path,
-- no branching that could regress the anonymity guarantee.
create or replace function public.submit_complaint(
  p_category text,
  p_message text,
  p_is_anonymous boolean,
  p_photo_path text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_contact_id uuid;
  v_id uuid;
begin
  if auth.uid() is null then
    raise exception 'not authorized';
  end if;

  if not p_is_anonymous then
    select c.id into v_contact_id
    from public.contacts c
    where c.email = (select au.email from public.app_users au where au.id = auth.uid());
  end if;

  if not p_is_anonymous and v_contact_id is null then
    raise exception 'could not resolve your contact record for a non-anonymous submission';
  end if;

  insert into public.complaints (category, message, is_anonymous, contact_id, photo_path)
  values (p_category, p_message, p_is_anonymous, v_contact_id, p_photo_path)
  returning id into v_id;

  return v_id;
end;
$$;

-- Lets the ORIGINAL SUBMITTER look up their own past complaints - a new
-- capability, reversing what the original design deferred as out of scope.
-- Named submissions are found via the same auth.uid() -> contact_id
-- resolution submit_complaint() already uses. Anonymous submissions have NO
-- server-side identity to resolve by design (true anonymity is unchanged) -
-- the caller must supply the exact complaint id(s) it received back at
-- submission time (meant to be remembered client-side, e.g. in localStorage)
-- as proof of having submitted it. Nothing here lets a caller fish for
-- someone else's anonymous complaint by guessing ids: every returned
-- anonymous row is exactly one the caller already explicitly named, and named
-- rows are still scoped to the caller's own resolved contact_id only.
create or replace function public.list_my_complaints(p_anonymous_ids uuid[] default '{}')
returns table (
  id uuid,
  complaint_number bigint,
  created_at timestamptz,
  category text,
  message text,
  is_anonymous boolean,
  status text,
  reviewer_comment text,
  photo_path text
)
language plpgsql
security definer
set search_path = public
stable
as $$
declare
  v_contact_id uuid;
begin
  if auth.uid() is null then
    raise exception 'not authorized';
  end if;

  select c.id into v_contact_id
  from public.contacts c
  where c.email = (select au.email from public.app_users au where au.id = auth.uid());

  return query
    select
      cx.id, cx.complaint_number, cx.created_at, cx.category, cx.message,
      cx.is_anonymous, cx.status, cx.reviewer_comment, cx.photo_path
    from public.complaints cx
    where (v_contact_id is not null and cx.contact_id = v_contact_id)
       or (cx.is_anonymous and cx.id = any(p_anonymous_ids))
    order by cx.created_at desc;
end;
$$;

